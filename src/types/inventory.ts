/**
 * Types and interface definitions for Room Check-In & Check-Out Audit & Property Inspection.
 * Handles digital room condition checklist (mattress, fan, sockets, door locks),
 * student/porter touchscreen signatures, check-out damage liability assessment,
 * and room inventory audit certificates.
 *
 * Designed with simple, clear English descriptions for non-technical stakeholders and hall porters.
 */

/**
 * Standard condition states for room fixtures and infrastructure.
 * - GOOD: Fully operational with no damage
 * - FAIR: Functional with minor wear
 * - POOR: Damaged or needs repair/maintenance
 */
export type ItemCondition = 'GOOD' | 'FAIR' | 'POOR';

/**
 * Inspection audit type classification.
 * - CHECK_IN: Initial room property check-in audit when student moves in
 * - CHECK_OUT: Final room property check-out audit when student vacates
 */
export type AuditType = 'CHECK_IN' | 'CHECK_OUT';

/**
 * Check-out student clearance status after property inspection.
 * - CLEARED: All room items intact, zero damage charges assessed
 * - DAMAGES_ASSESSED: Room defects or missing property found, damage liability fee charged
 * - PENDING: Inspection in progress or awaiting clearance review
 */
export type CheckoutStatus = 'CLEARED' | 'DAMAGES_ASSESSED' | 'PENDING';

/**
 * Interface representing a room property check-in or check-out audit record.
 */
export interface RoomInventoryAudit {
  // Unique identification code for this audit record
  id: string;
  // Room identification code
  roomId: string;
  // Room designation label (e.g. "Room 101, Block A")
  roomNumber?: string;
  // Unique student user ID assigned to the room
  studentId: string;
  // Student full name
  studentName?: string;
  // Student matriculation or staff number
  studentMatricNo?: string;
  // Unique porter/staff user ID conducting the joint inspection
  porterId: string;
  // Porter full name
  porterName?: string;
  // Physical condition of assigned bed mattress
  mattressCondition: ItemCondition;
  // Physical condition of ceiling fan / regulator
  fanCondition: ItemCondition;
  // Physical condition of electrical wall sockets
  socketsCondition: ItemCondition;
  // Physical condition of room door lock & window latches
  locksCondition: ItemCondition;
  // URL or base64 string of student digital touchscreen signature
  studentSignatureUrl?: string;
  // URL or base64 string of porter digital touchscreen signature
  porterSignatureUrl?: string;
  // Indicates if student digital touchscreen signature was verified
  hasStudentSignature?: boolean;
  // Indicates if porter digital touchscreen signature was verified
  hasPorterSignature?: boolean;
  // List of auto-generated property defect tickets for items marked POOR
  autoGeneratedDefects?: string[];
  // Inspection notes or property defect observations
  notes?: string;
  // Inspection audit type (CHECK_IN or CHECK_OUT)
  auditType?: AuditType;
  // Student clearance status for check-out inspections
  checkoutStatus?: CheckoutStatus;
  // Total damage liability fee charged to student for damaged/missing property
  damageFee?: number;
  // Exact date and time when the audit was recorded
  auditedAt: string;
}

/**
 * Parameters provided by porter when submitting a room check-in or check-out inventory audit.
 */
export interface RecordAuditParams {
  roomId: string;
  studentId: string;
  porterId: string;
  mattressCondition: ItemCondition;
  fanCondition: ItemCondition;
  socketsCondition: ItemCondition;
  locksCondition: ItemCondition;
  studentSignatureUrl?: string;
  porterSignatureUrl?: string;
  notes?: string;
  auditType?: AuditType;
  damageFee?: number;
}
