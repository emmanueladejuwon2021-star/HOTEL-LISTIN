import { create } from 'zustand';
import { RoomInventoryAudit, RecordAuditParams, DefectTicket } from '../types/inventory';
import { InventoryService } from '../api/inventoryService';

export interface InventoryState {
  audits: RoomInventoryAudit[];
  selectedAudit: RoomInventoryAudit | null;
  roomDefects: DefectTicket[];
  isLoading: boolean;
  errorMessage: string | null;
  successMessage: string | null;

  // Actions
  recordAudit: (params: RecordAuditParams) => Promise<RoomInventoryAudit | null>;
  fetchAuditsByStudent: (studentId: string) => Promise<void>;
  fetchAuditsByRoom: (roomId: string) => Promise<void>;
  fetchDefectsByRoom: (roomId: string) => Promise<void>;
  clearMessages: () => void;
}

export const useInventoryStore = create<InventoryState>((set) => ({
  audits: [],
  selectedAudit: null,
  roomDefects: [],
  isLoading: false,
  errorMessage: null,
  successMessage: null,

  recordAudit: async (params: RecordAuditParams) => {
    set({ isLoading: true, errorMessage: null, successMessage: null });
    try {
      const audit = await InventoryService.recordAudit(params);
      const defectCount = audit.autoGeneratedDefects?.length || 0;
      const defectNote = defectCount > 0
        ? ` (${defectCount} property defect ticket${defectCount > 1 ? 's' : ''} auto-dispatched to maintenance)`
        : '';

      set((state) => ({
        audits: [audit, ...state.audits],
        selectedAudit: audit,
        isLoading: false,
        successMessage: `Room inventory check-in audit recorded successfully for Room ${params.roomId}.${defectNote}`
      }));
      return audit;
    } catch (error: any) {
      set({
        errorMessage: error.message || 'Failed to record room inventory check-in audit.',
        isLoading: false
      });
      return null;
    }
  },

  fetchAuditsByStudent: async (studentId: string) => {
    set({ isLoading: true, errorMessage: null });
    try {
      const audits = await InventoryService.getAuditsByStudent(studentId);
      set({ audits, isLoading: false });
    } catch (error: any) {
      set({
        errorMessage: error.message || 'Failed to fetch student room inventory audits.',
        isLoading: false
      });
    }
  },

  fetchAuditsByRoom: async (roomId: string) => {
    set({ isLoading: true, errorMessage: null });
    try {
      const audits = await InventoryService.getAuditsByRoom(roomId);
      set({ audits, isLoading: false });
    } catch (error: any) {
      set({
        errorMessage: error.message || 'Failed to fetch room inventory audits.',
        isLoading: false
      });
    }
  },

  fetchDefectsByRoom: async (roomId: string) => {
    set({ isLoading: true, errorMessage: null });
    try {
      const defects = await InventoryService.getAutoDefectsByRoom(roomId);
      set({ roomDefects: defects, isLoading: false });
    } catch (error: any) {
      set({
        errorMessage: error.message || 'Failed to fetch room defect tickets.',
        isLoading: false
      });
    }
  },

  clearMessages: () => set({ errorMessage: null, successMessage: null })
}));
